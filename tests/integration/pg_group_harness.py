HERE = Path(__file__).resolve().parent
COMPOSE = HERE / "fixture_pg.compose.yaml"
IMAGE = ("postgres:16.10-bookworm@sha256:"
         "38471f330eb885e04de130b768d6db4e10469e2311879c7e5c699f6d2d8a1c74")
LABEL = "org.openai.maintain-server-containers.test"
FORMAT = "msc-synthetic-postgres-group/v1"
MEMBERS = ("db", "worker")
FILE_NAME = re.compile(r"^asset-[a-f0-9]{12}\.bin$")
PROJECT = re.compile(r"^msc-pg-(original|restored)-[a-f0-9]{12}$")

# Pure, read-only recovery proof contract. Not an action authorization.
