def _checksum(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha_file(path: Path) -> str:
    return _checksum(path.read_bytes())


def _db_command(container: str, args: list[str], *, payload: bytes | None = None) -> bytes:
    if not re.fullmatch(r"[a-f0-9]{12,64}", container):
        raise RuntimeError("REFUSED: invalid scoped container identity")
    approved = {"psql", "pg_dump", "pg_restore"}
    if not args or args[0] not in approved:
        raise RuntimeError("REFUSED: unapproved test database command")
    try:
        result = subprocess.run(["docker", "exec", "-i", container] + args, input=payload,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                check=False, timeout=40)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError("synthetic database operation failed") from exc
    if result.returncode:
        raise RuntimeError("synthetic database command rejected")
    if len(result.stdout) > 2_000_000:
        raise RuntimeError("REFUSED: synthetic SQL output over bound")
    return result.stdout


def compose_cmd(project: str) -> list[str]:
    if not PROJECT.fullmatch(project):
        raise RuntimeError("REFUSED: invalid fixture namespace")
    return ["docker", "compose", "--env-file", "/dev/null", "-f", str(COMPOSE),
            "--project-name", project]


def compose_env(assets: Path) -> dict[str, str]:
    return dict(os.environ, MSC_PG_ASSETS=str(assets))


def validate_compose(project: str, assets: Path) -> None:
    parsed = json.loads(_run(compose_cmd(project) + ["config", "--format", "json"],
                             env=compose_env(assets)))
    services = parsed.get("services", {})
    network = parsed.get("networks", {}).get("isolated", {})
    if set(services) != set(MEMBERS) or not isinstance(network, dict) or network.get("internal") is not True:
        raise RuntimeError("REFUSED: synthetic group/network scope changed")
    for member in MEMBERS:
        svc = services[member]
        if (svc.get("image") != IMAGE
                or svc.get("user") != "999:999"
                or svc.get("read_only") is not True
                or svc.get("privileged", False)
                or set(svc.get("cap_drop", [])) != {"ALL"}
                or "no-new-privileges:true" not in svc.get("security_opt", [])
                or not svc.get("pids_limit")
                or not svc.get("mem_limit")
                or set(svc.get("networks", {})) != {"isolated"}
                or svc.get("ports")
                or svc.get("labels", {}).get(LABEL) != "true"
                or any(k in svc for k in ("build", "devices", "secrets", "extra_hosts"))):
            raise RuntimeError("REFUSED: synthetic Compose service isolation changed")
    db = services["db"]
    required_tmpfs = {"/var/lib/postgresql/data", "/var/run/postgresql", "/tmp"}
    entries = db.get("tmpfs", [])
    if (db.get("volumes") or not isinstance(entries, list)
            or {x.split(":", 1)[0] for x in entries} != required_tmpfs):
        raise RuntimeError("REFUSED: PostgreSQL state is not strictly tmpfs")
    worker_tmpfs = services["worker"].get("tmpfs", [])
    if (not isinstance(worker_tmpfs, list)
            or {x.split(":", 1)[0] for x in worker_tmpfs} != {"/var/lib/postgresql/data"}):
        raise RuntimeError("REFUSED: worker may create anonymous PostgreSQL volume")
    mounts = services["worker"].get("volumes", [])
    if (len(mounts) != 1 or mounts[0].get("type") != "bind"
            or mounts[0].get("source") != str(assets)
            or mounts[0].get("target") != "/assets"
            or mounts[0].get("read_only") is not True
            or mounts[0].get("bind", {}).get("create_host_path") not in (False, None)):
        raise RuntimeError("REFUSED: synthetic file ownership scope changed")


def owned_ids(project: str, assets: Path) -> dict[str, str]:
    found = {}
    for identifier in containers(project):
        info = json.loads(_run(["docker", "inspect", identifier]))[0]
        labels = info.get("Config", {}).get("Labels", {})
        service = labels.get("com.docker.compose.service")
        mounts = info.get("Mounts", [])
        hc = info.get("HostConfig", {})
        if (service not in MEMBERS or service in found
                or labels.get(LABEL) != "true"
                or labels.get("com.docker.compose.project") != project
                or info.get("Config", {}).get("Image") != IMAGE
                or hc.get("Privileged") or hc.get("ReadonlyRootfs") is not True
                or hc.get("NetworkMode") != project + "_isolated"
                or hc.get("PortBindings")
                or any(m.get("Type") not in ("tmpfs", "bind") for m in mounts)):
            raise RuntimeError("REFUSED: synthetic runtime ownership or privilege drift")
        actual_binds = [m for m in mounts if m.get("Type") == "bind"]
        if service == "db" and actual_binds:
            raise RuntimeError("REFUSED: unapproved persistent PostgreSQL mount")
        if service == "worker" and (
                len(actual_binds) != 1
                or actual_binds[0].get("Source") != str(assets)
                or actual_binds[0].get("Destination") != "/assets"
                or actual_binds[0].get("RW") is not False):
            raise RuntimeError("REFUSED: synthetic worker bind changed")
        found[service] = identifier
    return found


def start(project: str, assets: Path) -> dict[str, str]:
    if containers(project):
        raise RuntimeError("REFUSED: synthetic Compose namespace is already in use")
    validate_compose(project, assets)
    _run(compose_cmd(project) + ["up", "-d", "--no-build", "--pull", "never"],
         env=compose_env(assets), timeout=160)
    end = time.monotonic() + 80
    while time.monotonic() < end:
        ids = owned_ids(project, assets)
        if set(ids) != set(MEMBERS):
            raise RuntimeError("synthetic F2 group is incomplete")
        states = [_run(["docker", "inspect", "--format", "{{.State.Health.Status}}", cid])
                  for cid in ids.values()]
        if all(s == "healthy" for s in states):
            return ids
        if "unhealthy" in states:
            raise RuntimeError("synthetic PostgreSQL worker group unhealthy")
        time.sleep(2)
    raise RuntimeError("synthetic PostgreSQL group health timed out")


def seed_files(assets: Path) -> dict:
    if assets.exists():
        raise ValueError("REFUSED: synthetic file destination already exists")
    assets.mkdir(mode=0o755)
    identity = secrets.token_hex(12)
    names = {}
    for _ in range(3):
        name = "asset-" + secrets.token_hex(6) + ".bin"
        data = ("pg-synthetic:" + identity + ":" + name).encode("ascii")
        (assets / name).write_bytes(data)
        names[name] = _checksum(data)
    return {"identity": identity, "files": names}


def _rows(db: str, *, remote: bool) -> tuple[str, dict]:
    connection = ["psql", "-X", "-q", "-A", "-t", "-v", "ON_ERROR_STOP=1"]
    if remote:
        connection += ["-h", "db"]
    connection += ["-U", "fixture", "-d", "fixture"]
    identity = _db_command(db, connection +
                           ["-c", "SELECT identifier FROM fixture_identity"]).decode("ascii").strip()
    lines = _db_command(db, connection +
                        ["-c", "SELECT name || ' ' || digest FROM attachment ORDER BY name"]).decode("ascii").splitlines()
    files = {}
    for line in lines:
        parts = line.split(" ")
        if len(parts) != 2 or not FILE_NAME.fullmatch(parts[0]) or not re.fullmatch(r"[a-f0-9]{64}", parts[1]):
            raise RuntimeError("synthetic PostgreSQL attachment references invalid")
        files[parts[0]] = parts[1]
    return identity, files


def assert_group(ids: dict, assets: Path, expected: dict) -> None:
    for service in MEMBERS:
        identity, referenced = _rows(ids[service], remote=service == "worker")
        if identity != expected["identity"] or referenced != expected["files"]:
            raise RuntimeError("synthetic PostgreSQL group SQL identity mismatch")
    if set(x.name for x in assets.iterdir()) != set(expected["files"]):
        raise RuntimeError("synthetic fixture attachments incomplete")
    for name, digest in expected["files"].items():
        path = assets / name
        if path.is_symlink() or _sha_file(path) != digest:
            raise RuntimeError("synthetic attachment digest mismatch")
        # Verify the independently running worker sees the exact same bytes.
        remote = _run(["docker", "exec", ids["worker"], "sha256sum", "/assets/" + name])
        if remote.split()[0] != digest:
            raise RuntimeError("synthetic worker file mismatch")


def seed_database(ids: dict, expected: dict) -> None:
    statements = [
        "BEGIN",
        "CREATE TABLE fixture_identity (identifier TEXT PRIMARY KEY)",
        "CREATE TABLE attachment (name TEXT PRIMARY KEY, digest TEXT NOT NULL)",
        f"INSERT INTO fixture_identity VALUES ('{expected['identity']}')",
    ]
    for name, digest in sorted(expected["files"].items()):
        statements.append(f"INSERT INTO attachment VALUES ('{name}', '{digest}')")
    statements.append("COMMIT")
    _db_command(ids["db"], ["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1",
                            "-U", "fixture", "-d", "fixture"],
                payload=(";\n".join(statements) + ";\n").encode("ascii"))


def verify_package(package: Path, *, expected: dict | None = None) -> dict:
    if not package.is_dir() or package.is_symlink():
        raise ValueError("synthetic group checkpoint missing")
    manifest_path = package / "manifest.json"
    if not manifest_path.is_file() or manifest_path.is_symlink():
        raise ValueError("synthetic group manifest missing")
    record = json.loads(manifest_path.read_text(encoding="utf-8"))
    keys = {"format", "members", "image", "source_digest", "identity", "files", "pg_dump_sha256"}
    if (not isinstance(record, dict) or set(record) != keys
            or record["format"] != FORMAT or record["members"] != list(MEMBERS)
            or record["image"] != IMAGE
            or record["source_digest"] != _sha_file(COMPOSE)
            or not isinstance(record["identity"], str)
            or not re.fullmatch(r"[a-f0-9]{24}", record["identity"])
            or not isinstance(record["files"], dict)
            or len(record["files"]) != 3
            or not re.fullmatch(r"[a-f0-9]{64}", record["pg_dump_sha256"])
            or any(not FILE_NAME.fullmatch(k) or
                   not isinstance(v, str) or not re.fullmatch(r"[a-f0-9]{64}", v)
                   for k, v in record["files"].items())):
        raise ValueError("synthetic checkpoint identity/group mismatch")
    if expected is not None and (record["identity"] != expected["identity"]
                                 or record["files"] != expected["files"]):
        raise ValueError("synthetic group checkpoint does not match source")
    if set(x.name for x in package.iterdir()) != {"manifest.json", "pg.dump", "assets"}:
        raise ValueError("synthetic checkpoint has unexpected files")
    dump = package / "pg.dump"
    if not dump.is_file() or dump.is_symlink() or _sha_file(dump) != record["pg_dump_sha256"]:
        raise ValueError("synthetic database dump damaged")
    folder = package / "assets"
    if not folder.is_dir() or folder.is_symlink() or set(x.name for x in folder.iterdir()) != set(record["files"]):
        raise ValueError("synthetic checkpoint incomplete")
    for name, digest in record["files"].items():
        path = folder / name
        if not path.is_file() or path.is_symlink() or _sha_file(path) != digest:
            raise ValueError("synthetic checkpoint file damaged")
    return {"identity": record["identity"], "files": record["files"]}


def capture(ids: dict, source: Path, target: Path, expected: dict) -> None:
    assert_group(ids, source, expected)
    if target.exists() or target.is_symlink():
        raise ValueError("REFUSED: checkpoint destination must be new")
    target.mkdir(mode=0o755)
    (target / "assets").mkdir()
    dump = _db_command(ids["db"], ["pg_dump", "-Fc", "-U", "fixture", "-d", "fixture",
                                    "--no-owner", "--no-privileges"])
    if not dump.startswith(b"PGDMP"):
        raise RuntimeError("synthetic PostgreSQL custom dump invalid")
    (target / "pg.dump").write_bytes(dump)
    for name in expected["files"]:
        shutil.copyfile(source / name, target / "assets" / name)
    assert_group(ids, source, expected)
    (target / "manifest.json").write_text(json.dumps({
        "format": FORMAT, "members": list(MEMBERS),
        "image": IMAGE, "source_digest": _sha_file(COMPOSE),
        "identity": expected["identity"], "files": expected["files"],
        "pg_dump_sha256": _checksum(dump),
    }, sort_keys=True) + "\n", encoding="utf-8")
    verify_package(target, expected=expected)


def restore_files(package: Path, destination: Path, *, expected: dict) -> None:
    verify_package(package, expected=expected)
    if destination.exists() or destination.is_symlink():
        raise ValueError("REFUSED: restore destination must be new")
    destination.mkdir(mode=0o755)
    for name in expected["files"]:
        shutil.copyfile(package / "assets" / name, destination / name)
    if any(_sha_file(destination / name) != expected["files"][name] for name in expected["files"]):
        raise RuntimeError("synthetic restored files differ")


def restore_database(ids: dict, package: Path, *, expected: dict) -> None:
    verify_package(package, expected=expected)
    _db_command(ids["db"], ["pg_restore", "--exit-on-error", "--no-owner",
                            "--no-privileges", "-U", "fixture", "-d", "fixture"],
                payload=(package / "pg.dump").read_bytes())


def teardown(project: str, assets: Path) -> None:
    ids = owned_ids(project, assets)
    if ids:
        _run(compose_cmd(project) + ["down", "--remove-orphans"], env=compose_env(assets),
             timeout=90)
    if containers(project):
        raise RuntimeError("REFUSED: synthetic group teardown left containers")
    # Only this project's Compose network may have been created.
    check = subprocess.run(["docker", "network", "inspect", project + "_isolated"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                           timeout=10, check=False)
    if check.returncode == 0:
        raise RuntimeError("REFUSED: synthetic Compose network not cleaned")


def run() -> None:
    temp = refuse_unless_ephemeral()
    if _run(["docker", "context", "show"]) != "default":
        raise RuntimeError("REFUSED: unexpected Docker context")
    sandbox = Path(tempfile.mkdtemp(prefix="msc-pg-disposable-", dir=temp))
    sandbox.chmod(0o755)
    suffix = secrets.token_hex(6)
    original_project = "msc-pg-original-" + suffix
    restored_project = "msc-pg-restored-" + suffix
    source = sandbox / "source-assets"
    restored = sandbox / "restored-assets"
    checkpoint = sandbox / "pg-recovery-set"
    damaged = sandbox / "damaged"
    fatal = None
    try:
        (sandbox / ".msc-restic-ci-only").write_text(TEST_MARKER + "\n", encoding="ascii")
        seed = seed_files(source)
        _run(["docker", "pull", IMAGE], timeout=180)
        original_ids = start(original_project, source)
        seed_database(original_ids, seed)
        assert_group(original_ids, source, seed)
        capture(original_ids, source, checkpoint, seed)
        # Corrupt an independent package. Never affect known good or start
        # any restore from a package that fails the complete inventory check.
        shutil.copytree(checkpoint, damaged)
        (damaged / "assets" / sorted(seed["files"])[0]).write_bytes(b"SYNTHETIC_DAMAGE")
        try:
            verify_package(damaged, expected=seed)
        except ValueError:
            pass
        else:
            raise RuntimeError("damaged synthetic PostgreSQL recovery set accepted")
        if restored.exists():
            raise RuntimeError("damaged checkpoint unexpectedly initiated restore")

        # H20: encrypted local Restic snapshot for the complete PostgreSQL group.
        # The direct test package MUST NOT be the source of restored app state.
        provider = PgResticFixture(sandbox)
        provider.initialize()
        snapshot_id = provider.capture_pg(
            checkpoint, validate=lambda item: verify_package(item, expected=seed),
        )
        group_recovery = {
            "schema": "recovery-set/v1", "application": "synthetic-pg-group",
            "compose": {"project": original_project,
                        "source_digest": "sha256:" + _sha_file(COMPOSE)},
            "images": {"db": IMAGE.split("@", 1)[1],
                       "worker": IMAGE.split("@", 1)[1]},
            "assets": [
                {"id": "pgdb", "kind": "database", "backend": "postgresql",
                 "consistency": "pg_dump", "reference": "synthetic-pg-database",
                 "recovery_required": True},
                {"id": "files", "kind": "user_files", "backend": "filesystem",
                 "consistency": "snapshot_quiesced", "reference": "synthetic-pg-files",
                 "recovery_required": True},
                {"id": "key", "kind": "secret_reference", "backend": "external_reference",
                 "consistency": "immutable_reference", "reference": "ci-key-responsibility",
                 "recovery_required": True},
            ],
        }
        declaration = validate_recovery_set(group_recovery)
        if not declaration.valid or not declaration.fingerprint:
            raise RuntimeError("synthetic PostgreSQL recovery-set identity invalid")
        proof = {
            "id": snapshot_id, "recovery_fingerprint": declaration.fingerprint,
            "class": "PRE_UPGRADE", "provider": "restic",
            "capture_complete": True, "repository_checked": True,
            "isolated_restore_tested": False, "application_smoke_passed": False,
            "holds": ["last_known_good"],
        }
        pending = validate_checkpoint(proof, recovery_fingerprint=declaration.fingerprint)
        if not pending.valid or pending.restore_tested:
            raise RuntimeError("premature PostgreSQL RESTORE_TESTED attestation")
        provider.reject_incorrect_password()
        # The password-failure test must not alter the working snapshot.
        provider.check_pg(snapshot_id, package=checkpoint)

        recovered_package = provider.restore_pg(
            snapshot_id, package=checkpoint,
            validate=lambda item: verify_package(item, expected=seed),
        )
        if recovered_package == checkpoint:
            raise RuntimeError("Restic recovery did not create isolated package")
        restore_files(recovered_package, restored, expected=seed)
        restored_ids = start(restored_project, restored)
        restore_database(restored_ids, recovered_package, expected=seed)
        assert_group(restored_ids, restored, seed)
        assert_group(original_ids, source, seed)
        verify_package(checkpoint, expected=seed)
        provider.check_pg(snapshot_id, package=checkpoint)
        proof["isolated_restore_tested"] = True
        proof["application_smoke_passed"] = True
        checked = validate_checkpoint(proof, recovery_fingerprint=declaration.fingerprint)
        if not checked.valid or not checked.restore_tested:
            raise RuntimeError("PostgreSQL Restic checkpoint lacks restore proof")
        retention = plan_retention_dry_run(
            declaration.fingerprint, [proof], [snapshot_id],
        )
        if retention.blockers or retention.permitted_candidates or len(retention.protected) != 1:
            raise RuntimeError("PostgreSQL known-good checkpoint not protected")
        print("F2-PG PASS PostgreSQL pg_dump + 3 files restored to separate two-service group",
              flush=True)
        print("F2-PG PASS incomplete/damaged group rejected, original unchanged", flush=True)
        print("H20 PASS encrypted PostgreSQL Restic exact snapshot, repository check, "
              "isolated two-service restore and protected known-good", flush=True)
        print("H21 PASS invalid Restic password refused and snapshot preserved", flush=True)
    except Exception as error:
        fatal = error
    finally:
        for project, files in ((restored_project, restored), (original_project, source)):
            try:
                teardown(project, files)
            except Exception as error:
                if fatal is None:
                    fatal = error
                print("FAIL owned PostgreSQL fixture cleanup", file=sys.stderr)
        if fatal is None:
            shutil.rmtree(sandbox)
            print("F2-PG PASS synthetic containers/network/tmpfs and temporary files cleaned",
                  flush=True)
        else:
            print("FAIL PostgreSQL fixture; run-owned diagnostics stay in ephemeral runner",
                  file=sys.stderr)
    if fatal is not None:
        raise RuntimeError("synthetic F2 PostgreSQL test failed safely") from fatal


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true")
    args = parser.parse_args()
    if not args.run:
        parser.error("REFUSED: --run and ephemeral GitHub Actions preflight required")
    run()
